def create_coco_subset(image_ids, original_coco_data):
    """
    Filters the original COCO dataset to create a subset based on a list of image IDs.
    """
    # Filter images
    subset_images = [img for img in original_coco_data['images'] if img['id'] in image_ids]

    # Filter annotations
    subset_annotations = [ann for ann in original_coco_data['annotations'] if ann['image_id'] in image_ids]

    # Create the subset COCO dictionary
    subset_coco_data = {
        'info': original_coco_data.get('info', {
            'description': 'COCO Subset',
            'version': '1.0',
            'year': datetime.datetime.now().year,
            'contributor': 'Colab DSA',
            'date_created': datetime.datetime.now().strftime('%Y-%m-%d %H:%M:%S')
        }),
        'licenses': original_coco_data.get('licenses', []),
        'images': subset_images,
        'annotations': subset_annotations,
        'categories': original_coco_data['categories']
    }
    return subset_coco_data

