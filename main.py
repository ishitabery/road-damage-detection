"""**Reasoning**:
The next step is to iterate through each dataset split (train, val, test), create necessary directories, copy images, and convert COCO annotations to YOLO format, saving them as .txt files in the respective 'labels' directories.


"""

IMG_DIR_SOURCE = IMG_DIR # Use the previously detected image directory as source

def convert_coco_to_yolo_split(coco_json_path, split_name, img_source_dir, yolo_base_dir, id_mapping):
    """
    Converts COCO annotations for a single split to YOLO format.
    """
    print(f"\nProcessing {split_name} split...")
    with open(coco_json_path, 'r') as f:
        coco_data_split = json.load(f)

    # Create directories for images and labels
    split_images_dir = yolo_base_dir / split_name / 'images'
    split_labels_dir = yolo_base_dir / split_name / 'labels'

    split_images_dir.mkdir(parents=True, exist_ok=True)
    split_labels_dir.mkdir(parents=True, exist_ok=True)

    # Create a mapping from image_id to image info (width, height, file_name)
    image_id_to_info = {img['id']: {'width': img['width'], 'height': img['height'], 'file_name': img['file_name']}
                        for img in coco_data_split['images']}

    # Group annotations by image_id
    annotations_by_image = defaultdict(list)
    for ann in coco_data_split['annotations']:
        annotations_by_image[ann['image_id']].append(ann)

    total_images_processed = 0
    total_annotations_processed = 0

    for img_id, img_info in image_id_to_info.items():
        original_image_filename = img_info['file_name']
        image_width = img_info['width']
        image_height = img_info['height']

        # Copy image file
        source_image_path = img_source_dir / original_image_filename
        dest_image_path = split_images_dir / original_image_filename
        if source_image_path.is_file():
            shutil.copy(source_image_path, dest_image_path)
            total_images_processed += 1
        else:
            print(f"Warning: Image file not found for {original_image_filename} at {source_image_path}. Skipping.")
            continue

        # Prepare YOLO label file
        label_filename = Path(original_image_filename).stem + '.txt'
        label_file_path = split_labels_dir / label_filename

        with open(label_file_path, 'w') as f_label:
            for ann in annotations_by_image.get(img_id, []):
                x_coco, y_coco, w_coco, h_coco = ann['bbox']
                class_id_coco = ann['category_id']

                # Convert to YOLO format
                x_center = (x_coco + w_coco / 2) / image_width
                y_center = (y_coco + h_coco / 2) / image_height
                bbox_width_norm = w_coco / image_width
                bbox_height_norm = h_coco / image_height

                # Map to YOLO 0-indexed class ID
                yolo_class_id = id_mapping.get(class_id_coco)

                if yolo_class_id is not None:
                    f_label.write(f"{yolo_class_id} {x_center} {y_center} {bbox_width_norm} {bbox_height_norm}\n")
                    total_annotations_processed += 1
                else:
                    print(f"Warning: Category ID {class_id_coco} not found in mapping for image {original_image_filename}. Skipping annotation.")

    print(f"  Copied {total_images_processed} images.")
    print(f"  Processed {total_annotations_processed} annotations.")


# Process each split
for split_name, coco_path in dataset_splits.items():
    convert_coco_to_yolo_split(coco_path, split_name, IMG_DIR_SOURCE, YOLO_DATA_BASE_DIR, original_id_to_yolo_id)

